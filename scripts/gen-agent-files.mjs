#!/usr/bin/env node
// Generate what each agent harness reads from the harness-neutral sources. (#271, ADR 0033)
//
// The sources are AGENTS.md, .agents/rules/, .agents/skills/ (every skill that no command generates)
// and .agents/commands/. Codex and opencode read AGENTS.md and .agents/skills/ themselves. Claude Code
// reads none of .agents/, and reads a root AGENTS.md only while no CLAUDE.md is on its startup chain --
// and Next.js's frontend/CLAUDE.md is one -- so it gets copies (measured on 2.1.312, #271):
//   - CLAUDE.md is AGENTS.md whole, under a header. Never an `@AGENTS.md` import: from a session
//     started in frontend/ the root's import did not load, and the copy did.
//   - .claude/rules/ is .agents/rules/ byte for byte. An `@` import there loads at session start and
//     ignores `paths:`, so the copy is the only way a scoped rule stays scoped.
//   - .claude/skills/ and .claude/commands/ are the source skills and commands, byte for byte.
// The commands also become Codex skills in .agents/skills/<command>/, opencode commands and
// opencode.json, as before (#252). The copies are files, not symlinks, because the product owner's
// colleagues work on Windows. Nothing is generated under frontend/, whose files belong to Next.js.
//
// Usage:
//   node scripts/gen-agent-files.mjs           write every generated file and scripts/agent-files.json
//   node scripts/gen-agent-files.mjs --check   exit 1, naming each problem, if anything has drifted
//
// Never edit a generated file: edit its source and re-run this. scripts/agent-files-pre-commit.mjs
// runs it on what is staged, from the hook in .githooks/; the drift test in `pnpm test` is the guarantee.
//
// Files are listed through git (tracked, plus untracked that .gitignore does not exclude), so an
// ignored `.DS_Store` never becomes a source; the pre-commit hook passes its own lister, fed from the
// index. A file under a generated directory that nothing generates is drift, and this script never
// deletes one it did not write: an untracked file deleted is gone.
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const LIST = 'scripts/agent-files.json';
export const NOT_DELIVERED = 'scripts/agent-files-not-delivered.json';
export const AGENTS_END = '<!-- END:backchannel-agents-md -->';
export const MARKER = 'Generated by scripts/gen-agent-files.mjs';
const RULES = '.agents/rules';
const SKILLS = '.agents/skills';
const COMMANDS = '.agents/commands';
const INDEX_HEADING = '## Rules scoped to paths: open the file before you read or edit what it governs';
// Every directory whose files are all generated, besides the command skills under .agents/skills/.
const GENERATED_ROOTS = ['.claude/rules', '.claude/skills', '.claude/commands', '.opencode/command', '.opencode/commands'];

// The files git would commit under a directory, relative to the repository, with `/` separators.
function gitFiles(repo, dir) {
  const out = execFileSync('git', ['-C', repo, 'ls-files', '-z', '--cached', '--others', '--exclude-standard', '--', dir], { encoding: 'utf8' });
  return [...new Set(out.split('\0').filter(Boolean))].filter((f) => fs.existsSync(path.join(repo, f)) || isLink(repo, f)).sort();
}
const isLink = (repo, f) => { try { return fs.lstatSync(path.join(repo, f)).isSymbolicLink(); } catch { return false; } };
const isFile = (repo, f) => { try { return fs.lstatSync(path.join(repo, f)).isFile(); } catch { return false; } };
const readLf = (repo, f) => fs.readFileSync(path.join(repo, f), 'utf8').replace(/\r\n/g, '\n');
// Line endings are normalized, so a Windows checkout with core.autocrlf compares equal -- in bytes,
// and only for text: a file holding a NUL is binary, as git's text=auto decides, and is compared as
// it is. Decoding as UTF-8 first folded invalid bytes together, so a corrupted binary copy read as
// equal (#271's gate adversary).
export const normalize = (b) => {
  const buf = Buffer.isBuffer(b) ? b : Buffer.from(b, 'utf8');
  return buf.includes(0) ? buf : Buffer.from(buf.toString('latin1').replace(/\r\n/g, '\n'), 'latin1');
};
const same = (a, b) => normalize(a).equals(normalize(b));

// How a run lists files: through git in a checkout, from the index in the pre-commit hook. `previous`
// is every target a list has named -- the committed one and the one on disk or staged -- which is what
// marks a skill directory as generated after its command is gone (#271's round-4 critic).
function context(repo, opts = {}) {
  const list = opts.list ?? ((dir) => gitFiles(repo, dir));
  const named = opts.previous ?? [...namedBy(readListFile(repo)), ...namedBy(headList(repo))];
  // A skill directory a list generated from a command stays generated. A list from before #271 names
  // .agents/skills/gopnik* too, generated from .claude/skills/, and those are sources now.
  const commandSkills = new Set(named.filter(([t, s]) => t.startsWith(`${SKILLS}/`) && [s].flat().some((x) => /(^|\/)commands\/[^/]+\.md$/.test(x))).map(([t]) => skillDir(t)));
  return { repo, list, previous: new Set(named.map(([t]) => t)), commandSkills };
}
function readListFile(repo) {
  try { return fs.readFileSync(path.join(repo, LIST), 'utf8'); } catch { return null; }
}
function headList(repo) {
  try { return execFileSync('git', ['-C', repo, 'show', `HEAD:${LIST}`], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }); } catch { return null; }
}
// The [target, source] pairs a list names.
export function namedBy(text) {
  if (!text) return [];
  try { return Object.entries(JSON.parse(text).files ?? {}); } catch { return []; }
}

const SCOPE = /^---\npaths:\n((?:\s+- .+\n)+)---\n/;

// The scoped rules, from their front matter: path -> globs.
export function scopedRules(repo = REPO, opts) {
  const { list } = context(repo, opts);
  return list(RULES).filter((f) => f.endsWith('.md')).flatMap((f) => {
    const m = SCOPE.exec(readLf(repo, f));
    return m ? [[f, [...m[1].matchAll(/- "?([^"\n]+)"?/g)].map((g) => g[1])]] : [];
  });
}

// The `@path` tokens Claude Code would import: an `@` at the start of a line or after whitespace,
// followed by a non-space, outside code spans and fenced blocks (neither imports, measured on #271).
// Fences as CommonMark has them: three or more backticks or tildes, closed only by the same character
// at least as many times; a backtick fence's info string holds no backtick. A fence toggled by any
// line starting with ``` let three shapes through that Claude Code 2.1.312 imports (#271's adversary).
export function atTokens(text) {
  const found = [];
  let fence = null;
  for (const line of text.replace(/\r\n/g, '\n').split('\n')) {
    const m = /^ {0,3}(`{3,}|~{3,})(.*)$/.exec(line);
    if (fence) {
      if (m && m[1][0] === fence[0] && m[1].length >= fence.length && !m[2].trim()) fence = null;
      continue;
    }
    if (m && !(m[1][0] === '`' && m[2].includes('`'))) { fence = m[1]; continue; }
    const prose = line.replace(/(`+)[\s\S]*?\1/g, ' ');
    for (const m of prose.matchAll(/(?:^|\s)(@[^\s`]+)/g)) found.push(m[1]);
  }
  return found;
}

// Which skill directories under .agents/skills/ are generated: one per command, and any a list named.
function commandNames(ctx) {
  return ctx.list(COMMANDS).filter((f) => f.endsWith('.md')).map((f) => path.basename(f, '.md'));
}
function generatedSkillDirs(ctx) {
  return new Set([...commandNames(ctx), ...ctx.commandSkills]);
}
function skillDir(f) { return f.slice(SKILLS.length + 1).split('/')[0]; }
function sourceSkillFiles(ctx) {
  const generated = generatedSkillDirs(ctx);
  return ctx.list(SKILLS).filter((f) => !generated.has(skillDir(f)));
}

// The index of scoped rules, as it must stand in AGENTS.md: each rule and every glob it names, and
// frontend/AGENTS.md, which Codex started at the root never loads.
export function indexRows(repo = REPO, opts) {
  return [...scopedRules(repo, opts).map(([f, globs]) => `| \`${f}\` | ${globs.map((g) => `\`${g}\``).join(', ')} |`),
    '| `frontend/AGENTS.md` | `frontend/**` (Next.js 16\'s own notes; Codex started at the root never reads it) |'];
}

// What is wrong with the sources themselves, before anything is generated from them.
export function lint(repo = REPO, opts) {
  const ctx = context(repo, opts);
  const problems = [];
  if (!isFile(repo, 'AGENTS.md')) return ['AGENTS.md is missing; it is the source of every harness\'s instructions'];
  const agents = readLf(repo, 'AGENTS.md');
  if (agents.includes(MARKER)) problems.push(`AGENTS.md says it is generated; it is the source, and CLAUDE.md is generated from it`);
  if (!agents.trimEnd().endsWith(AGENTS_END)) problems.push(`AGENTS.md does not end with ${AGENTS_END}`);
  for (const t of atTokens(agents)) problems.push(`AGENTS.md has ${t}, which Claude Code would import; write the path in backticks`);
  for (const f of ctx.list(RULES).filter((f) => f.endsWith('.md'))) {
    const text = readLf(repo, f);
    if (!SCOPE.test(text)) problems.push(`${f} has no \`paths:\` front matter; a rule every session needs belongs in AGENTS.md, or Claude Code would load it twice`);
    for (const t of atTokens(text)) problems.push(`${f} has ${t}, which Claude Code would import at session start, ignoring paths:`);
  }
  // The index, by rows: every scoped rule with each glob, frontend/AGENTS.md, and nothing else.
  const at = agents.indexOf(INDEX_HEADING);
  if (at < 0) problems.push(`AGENTS.md has no "${INDEX_HEADING}" section`);
  else {
    const have = agents.slice(at).split('\n').filter((l) => /^\| `/.test(l));
    const want = indexRows(repo, opts);
    for (const r of want.filter((r) => !have.includes(r))) problems.push(`AGENTS.md's index lacks the row ${r}`);
    for (const r of have.filter((r) => !want.includes(r))) problems.push(`AGENTS.md's index has a row no scoped rule gives: ${r}`);
  }
  for (const f of sourceSkillFiles(ctx).filter((f) => f.endsWith('SKILL.md'))) {
    if (readLf(repo, f).includes(MARKER)) problems.push(`${f} carries "${MARKER}" but nothing generates it; a generated skill is never a source`);
  }
  return problems;
}

function command(repo, f) {
  const text = readLf(repo, f);
  const m = /^---\n([\s\S]*?)\n---\n/.exec(text);
  if (!m) throw new Error(`${f} has no front matter`);
  const description = /^description:\s*(.+)$/m.exec(m[1])?.[1];
  if (!description) throw new Error(`${f} has no description`);
  return { name: path.basename(f, '.md'), description, body: text.slice(m[0].length).replace(/^\n+/, '') };
}

// The commands become skills for Codex and opencode, and commands for opencode (#252). Codex has no
// project commands: `$work 42` names the skill and injects its body. In Codex `$issue` is the mention
// of the skill that opens issues, so the skills carry no `$issue`; the number is written N. opencode's
// commands put the argument where the command had it, as `$1`, and append free text to `issue`,
// which has no placeholder. `issue` creates GitHub issues, so it is never invoked implicitly: Codex
// lists it only when named (`allow_implicit_invocation: false`), and opencode asks first (`opencode.json`).
const NO_IMPLICIT = ['issue'];

// A command names its siblings as Claude Code invokes them (`/critique 42`). The skills are read by Codex,
// which invokes them as `$critique 42`, and by opencode, which uses `/critique 42`: they name both.
const asSkill = (body) => body.replace(/`\/(critique|issue|work)([^`]*)`/g, '`$$$1$2` in Codex, `/$1$2` in opencode');

function commandFiles(ctx) {
  const out = [];
  for (const f of ctx.list(COMMANDS).filter((f) => f.endsWith('.md'))) {
    const { name, description, body } = command(ctx.repo, f);
    const numbered = body.includes('$issue');
    const skill = [
      `---\nname: ${name}\ndescription: ${description}\n---\n`,
      `<!-- ${MARKER} from ${f}. Edit that and re-run it; never this file. -->\n`,
      numbered ? 'The issue number comes with the request that invoked this skill, as in `$' + name + ' 42` in Codex or `/' + name + ' 42` in opencode. It is written **N** below.\n' : '',
      asSkill(numbered ? body.replaceAll('**$issue**', '**N**').replaceAll('$issue', 'N') : body),
    ].join('\n');
    out.push([`${SKILLS}/${name}/SKILL.md`, f, skill]);
    if (NO_IMPLICIT.includes(name)) {
      out.push([`${SKILLS}/${name}/agents/openai.yaml`, f,
        `# ${MARKER} from ${f}. ${name} acts on GitHub, so Codex loads it only when it is named.\npolicy:\n  allow_implicit_invocation: false\n`]);
    }
    const cmd = [
      `---\ndescription: ${description}\n---\n`,
      `<!-- ${MARKER} from ${f}. Edit that and re-run it; never this file. -->\n`,
      numbered ? body.replaceAll('$issue', '$1') : body,
      // opencode's last placeholder takes every remaining word (1.18.32: `slice(i).join(" ")`), so
      // without a `$2` after it, `/work 42 please` would put "42 please" wherever the number goes.
      numbered ? 'Anything else the request said: $2\n' : '',
    ].join('\n');
    out.push([`.opencode/command/${name}.md`, f, cmd]);
  }
  const asks = commandNames(ctx).filter((n) => NO_IMPLICIT.includes(n));
  out.push(['opencode.json', asks.map((n) => `${COMMANDS}/${n}.md`),
    `${JSON.stringify({ $schema: 'https://opencode.ai/config.json', permission: { skill: Object.fromEntries(asks.map((n) => [n, 'ask'])) } }, null, 2)}\n`]);
  return out;
}

const claudeMd = (repo) => Buffer.from(`<!-- ${MARKER} from AGENTS.md. Edit that and re-run it; never this file. -->\n\n${readLf(repo, 'AGENTS.md')}`, 'utf8');

// What should exist: generated path -> { source, content }. A source is a path, or a list of them.
export function plan(repo = REPO, opts) {
  const ctx = context(repo, opts);
  const out = new Map();
  if (!isFile(repo, 'AGENTS.md')) throw new Error('AGENTS.md is missing; it is the source of every harness\'s instructions');
  out.set('CLAUDE.md', { source: 'AGENTS.md', content: claudeMd(repo) });
  const copy = (source, target) => {
    if (!isFile(repo, source)) throw new Error(`${source} is not a regular file; a source is copied as files, never as links`);
    out.set(target, { source, content: fs.readFileSync(path.join(repo, source)) });
  };
  for (const f of ctx.list(RULES)) copy(f, f.replace(/^\.agents\//, '.claude/'));
  for (const f of sourceSkillFiles(ctx)) copy(f, f.replace(/^\.agents\//, '.claude/'));
  for (const f of ctx.list(COMMANDS)) copy(f, f.replace(/^\.agents\//, '.claude/'));
  for (const [target, source, text] of commandFiles(ctx)) out.set(target, { source, content: Buffer.from(text, 'utf8') });
  return out;
}

export function listOf(files) {
  return `${JSON.stringify({
    comment: `${MARKER}. Each key is generated from its value; edit the value and re-run the script, never the key. (#233, #271)`,
    files: Object.fromEntries([...files].map(([target, { source }]) => [target, source])),
  }, null, 2)}\n`;
}

// Files under the generated directories that the plan does not produce.
function strays(ctx, files) {
  const roots = [...GENERATED_ROOTS, ...[...generatedSkillDirs(ctx)].map((d) => `${SKILLS}/${d}`)];
  return [...new Set(roots.flatMap((root) => ctx.list(root)))].filter((f) => !files.has(f)).sort();
}

// The strays, for the pre-commit hook, which decides itself what to remove.
export function strayFiles(repo, opts, files) {
  return strays(context(repo, opts), files);
}

export function drift(repo = REPO, opts) {
  const ctx = context(repo, opts);
  const problems = lint(repo, opts);
  let files;
  try { files = plan(repo, opts); } catch (e) { return [...problems, e.message]; }
  const listPath = path.join(repo, LIST);
  if (!fs.existsSync(listPath)) problems.push(`${LIST} is missing`);
  else if (!same(fs.readFileSync(listPath), listOf(files))) problems.push(`${LIST} does not name what the sources generate`);
  for (const [target, { source, content }] of files) {
    if (isLink(repo, target)) problems.push(`${target} is a link; a generated file is a copy`);
    else if (!isFile(repo, target)) problems.push(`${target} is missing (from ${[source].flat().join(', ')})`);
    else if (!same(fs.readFileSync(path.join(repo, target)), content)) problems.push(`${target} differs from ${[source].flat().join(', ')}`);
  }
  for (const f of strays(ctx, files)) problems.push(`${f} is not generated from anything; remove it or give it a source in .agents/`);
  return problems;
}

// Write the plan. Remove only what a list named; refuse, naming it, anything else.
export function write(repo = REPO, opts) {
  const ctx = context(repo, opts);
  const problems = lint(repo, opts);
  if (problems.length) return { ok: false, lines: [...problems, 'Nothing was written.'] };
  const files = plan(repo, opts);
  const unknown = strays(ctx, files).filter((f) => !ctx.previous.has(f));
  if (unknown.length) {
    return { ok: false, lines: unknown.map((f) => `${f} is under a generated directory, and nothing generated it; move it to its source in .agents/. Nothing was written.`) };
  }
  const lines = [];
  for (const f of strays(ctx, files)) { fs.rmSync(path.join(repo, f)); lines.push(`removed ${f}, which its source no longer generates`); }
  for (const [target, { content }] of files) {
    if (isLink(repo, target)) fs.rmSync(path.join(repo, target));
    fs.mkdirSync(path.dirname(path.join(repo, target)), { recursive: true });
    fs.writeFileSync(path.join(repo, target), content);
  }
  fs.writeFileSync(path.join(repo, LIST), listOf(files));
  lines.push(`wrote ${files.size} files and ${LIST}`);
  return { ok: true, lines };
}

// Resolved on both sides: a checkout reached through a symlink must not skip the whole script.
const invoked = process.argv[1] && fs.existsSync(process.argv[1]) && fs.realpathSync(process.argv[1]) === fs.realpathSync(fileURLToPath(import.meta.url));
if (invoked) {
  if (process.argv.includes('--check')) {
    const problems = drift();
    for (const p of problems) console.error(`gen-agent-files: ${p}`);
    if (!problems.length) console.log('gen-agent-files: every generated file matches its source');
    process.exit(problems.length ? 1 : 0);
  }
  const { ok, lines } = write();
  for (const l of lines) (ok ? console.log : console.error)(`gen-agent-files: ${l}`);
  process.exit(ok ? 0 : 1);
}
