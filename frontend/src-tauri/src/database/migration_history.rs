//! Migrations applied to a database that already has rows.
//!
//! #63. Every test in this crate applied the seventeen migrations to an empty database —
//! `migrated_pool()` in `repositories/transcript.rs` connects to `sqlite::memory:` and migrates
//! it, and production's `manager.rs:35` is the only other call site. So **eight migrations whose
//! whole purpose is to change rows that already exist have never, in any test, changed one.**
//! A migration that runs over zero rows and a migration that does the wrong thing are
//! indistinguishable in a green suite, which is the state this file ends.
//!
//! The eight, by the rule *"contains at least one statement whose effect depends on rows that
//! existed before it ran"*:
//!
//! | version | what depends on existing rows |
//! |---|---|
//! | `20250920155811` | `INSERT INTO settings_new SELECT *` — a **positional** copy |
//! | `20251105120000` | `DROP TABLE IF EXISTS licensing` and recreate |
//! | `20251110000000` | `ADD COLUMN … NOT NULL DEFAULT 604800` — writes every row |
//! | `20260806000000` | `UPDATE … WHERE provider IN (…)` |
//! | `20260806000001` | two `UPDATE`s |
//! | `20260806000002` | two `UPDATE`s, **order-dependent** |
//! | `20260807000000` | `DROP TABLE IF EXISTS licensing` |
//! | `20260811000000` | an explicit backfill, two `INSERT … SELECT` |
//!
//! **Why `run_to` and not `.sqlite` fixtures.** `git diff --stat v1.2.0 HEAD -- migrations/` and
//! `v1.4.1 HEAD` show migrations 1–16 are byte-identical to their tags, so
//! `Migrator::run_to(version, pool)` reproduces every shipped schema from the same source of
//! truth. A committed binary would be a second source that could drift from it, and could only
//! be regenerated by the code it exists to check.
//!
//! **Not here, deliberately:** the legacy `.db` import path. It fails today with
//! `duplicate column name: folder_path` (#68), and covering it here would make this suite red for
//! a defect this change does not fix.
#![cfg(test)]

use sqlx::migrate::Migrator;
use sqlx::sqlite::SqlitePoolOptions;
use sqlx::{Row, SqlitePool};

static MIGRATOR: Migrator = sqlx::migrate!("./migrations");

// The eight versions above, named rather than repeated as literals at each call site.
const SETTINGS_REBUILD: i64 = 20250920155811;
const LICENSING_RECREATE: i64 = 20251105120000;
const GRACE_PERIOD: i64 = 20251110000000;
const COLLAPSE_LOCAL: i64 = 20260806000000;
const REPAIR_STALE: i64 = 20260806000001;
const BUILTIN_AUDIO: i64 = 20260806000002;
const DROP_LICENSING: i64 = 20260807000000;
const SEARCH_BACKFILL: i64 = 20260811000000;

/// A pool migrated up to and including `version`, and no further.
///
/// `max_connections(1)`: every connection to `sqlite::memory:` opens its own database, so a
/// multi-connection pool would migrate one and query another — the same reason
/// `repositories/transcript.rs` says so.
async fn schema_at(version: i64) -> SqlitePool {
    let pool = SqlitePoolOptions::new()
        .max_connections(1)
        .connect("sqlite::memory:")
        .await
        .expect("in-memory sqlite");
    apply(&pool, version).await;
    pool
}

/// The schema immediately before `version` — where a fixture is seeded so that `version` has
/// something to transform.
async fn schema_before(version: i64) -> SqlitePool {
    let previous = MIGRATOR
        .iter()
        .map(|m| m.version)
        .filter(|&v| v < version)
        .max()
        .unwrap_or_else(|| panic!("{version} is the first migration; nothing precedes it"));
    schema_at(previous).await
}

/// `Acquire` is implemented for `&Pool` with the pool's own lifetime, which a `&SqlitePool`
/// parameter cannot satisfy inside an `async fn`. Acquiring a connection first sidesteps that:
/// `&mut SqliteConnection` implements `Acquire` with a lifetime this function owns. The single
/// connection is also what `sqlite::memory:` requires — see `schema_at`.
async fn apply(pool: &SqlitePool, version: i64) {
    let mut conn = pool.acquire().await.expect("a connection from the pool");
    MIGRATOR
        .run_to(version, &mut *conn)
        .await
        .unwrap_or_else(|e| panic!("applying {version} failed: {e}"));
}

async fn run_all(pool: &SqlitePool) {
    let mut conn = pool.acquire().await.expect("a connection from the pool");
    MIGRATOR
        .run(&mut *conn)
        .await
        .expect("a populated database migrates to head");
}

/// `&'static str` and a bound parameter rather than a formatted string: sqlx 0.9 refuses
/// dynamic SQL outright ("dynamic SQL strings should be audited for possible injections"), and
/// interpolating an id into a query in a test is how the habit reaches production.
async fn one_string(pool: &SqlitePool, sql: &'static str, bind: &str) -> String {
    let mut conn = pool.acquire().await.expect("a connection");
    sqlx::query(sql)
        .bind(bind.to_owned())
        .fetch_one(&mut *conn)
        .await
        .unwrap_or_else(|e| panic!("{sql} [{bind}]: {e}"))
        .get::<String, _>(0)
}

async fn count(pool: &SqlitePool, sql: &'static str) -> i64 {
    let mut conn = pool.acquire().await.expect("a connection");
    sqlx::query(sql)
        .fetch_one(&mut *conn)
        .await
        .unwrap_or_else(|e| panic!("{sql}: {e}"))
        .get::<i64, _>(0)
}

