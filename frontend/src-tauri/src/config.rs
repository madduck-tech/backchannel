/// Base URL for catalog downloads. Every model above lives under this org.
pub const TRANSCRIBE_MODEL_BASE_URL: &str = "https://huggingface.co/handy-computer";

/// Look up a catalog row by its stored name.
/// Catalog variants that attribute speakers, by name prefix so every
/// quantization tier is covered.
///
/// Not the family: `Granite Speech` holds three variants and only `-plus`
/// diarizes — the base does not advertise it and `-nar` documents its absence.
/// Not `Capabilities` either, which carries no diarization bit to read.
pub const DIARIZING_VARIANTS: &[&str] =
    &["granite-speech-4.1-2b-plus", "moss-transcribe-diarize"];

pub fn model_diarizes(name: &str) -> bool {
    transcribe_model(name)
        .is_some_and(|m| DIARIZING_VARIANTS.iter().any(|v| m.name.starts_with(v)))
}

/// The speaker diarizer, deliberately *not* a [`TRANSCRIBE_MODEL_CATALOG`] row.
///
/// It emits speaker turns and never text, so it can never be picked as a
/// transcription model — which is exactly why it is a const instead of a
/// catalog entry with a "not selectable" flag. Every consumer of the catalog
/// (the picker, `discover_models`, `exactly_the_documented_variants_diarize`)
/// would otherwise need a branch for the one row that is not a transcription
/// model, and `gen_model_catalog.py`'s exclusion comment would stop being true.
///
/// `TranscribeEngine::download_diarizer` passes its repository, file, revision,
/// size and sha256 to the engine's private `download_file`, so those fields are the
/// whole download integration. The licence fields and the upstream repository
/// carry its credit (ADR 0030).
pub struct DiarizerModel {
    pub hf_repo: &'static str,
    /// Held equal to the generator's map entry for its record by
    /// `test_the_diarizer_carries_its_records_licence` (#197).
    pub license_name: &'static str,
    pub license_url: &'static str,
    pub license_mark: LicenceMark,
    pub upstream_repo: &'static str,
    pub filename: &'static str,
    pub size_mb: u64,
    /// Pinned by the same rule as a catalog row's (#179), between markers of their
    /// own that the generator writes.
    pub revision: &'static str,
    pub size_bytes: u64,
    pub sha256: &'static str,
    /// Architectural cap. A fifth speaker is silently folded into one of the
    /// four arrival-order slots — there is no signal that it happened.
    pub max_speakers: u32,
}

/// `nvidia/diar_streaming_sortformer_4spk-v2.1`, Q8_0.
