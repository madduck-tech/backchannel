/// One catalog row: a single quantization of a single transcribe.cpp variant.
#[derive(Debug, Clone, Copy)]
pub struct TranscribeModel {
    /// Stable identifier stored in `transcript_settings.model`.
    pub name: &'static str,
    /// Display family, e.g. "Whisper". The picker groups by this.
    pub family: &'static str,
    pub hf_repo: &'static str,
    pub filename: &'static str,
    /// Decimal MB of the file's bytes, `round(size_bytes / 10⁶)` of upstream's
    /// catalogue record at the pinned revision (#175). The availability floor
    /// (`TranscribeEngine::available_floor_bytes`) reads the same unit. The one
    /// exception is a row in the generator's `HOLD` list.
    pub size_mb: u32,
    pub accuracy: &'static str,
    /// Measured word error rate for this exact quantization, from upstream's
    /// catalogue: LibriSpeech test-clean, or the set the family names (FLEURS ru
    /// for GigaAM). `None` when it publishes none.
    ///
    /// Shown as a number in the picker, so it travels with `wer_set`: 1.27% on
    /// English read speech and 5.50% on Russian are not two points on one scale,
    /// and without the set beside it the smaller number reads as the better
    /// model. `accuracy` above is this number bucketed.
    pub wer: Option<f32>,
    /// The evaluation set `wer` was measured on; empty when `wer` is `None`.
    pub wer_set: &'static str,
    pub speed: &'static str,
    /// Whether the application streams this variant live, word by word.
    ///
    /// Display only — it decides the live tag in the picker before the GGUF exists
    /// on disk. The decode path is chosen by `audio::transcription::live_path` from
    /// the loaded model's capabilities, which are read from GGUF metadata and
    /// cannot drift. A model that streams but whose stream is capped
    /// (moonshine_streaming) is false here, because it is decoded in segments
    /// (#200).
    pub streaming: bool,
    /// The languages upstream's catalogue says the port transcribes, equal to the
    /// GGUF's own `general.languages` on every row (#175). Codes rather than
    /// prose, because the UI renders names from them and a language filter needs
    /// the list itself. The blurb this replaced drifted: it claimed 39 locales
    /// for nemotron-3.5, whose GGUF says 32.
    pub languages: &'static [&'static str],
    /// The licence's SPDX id from upstream's catalogue ("other" when it has
    /// none). Carried, not yet acted on: which licences may be offered is #197.
    pub license: &'static str,
    pub description: &'static str,
}

