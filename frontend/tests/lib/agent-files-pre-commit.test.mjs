// The pre-commit hook regenerates the agent files from what is staged, and refuses rather than lose
// anything. (#271, ADR 0033)
//
// .githooks/pre-commit runs scripts/agent-files-pre-commit.mjs; `prepare` in frontend/package.json
// installs it through scripts/install-git-hooks.mjs. Each case is condition 5 of #271, in a fixture
// repository of its own with the hook installed the way `pnpm install` installs it. The hook is a
// convenience and the drift test is the guarantee, so what is held here is that it never commits a copy
// of text that is not in the commit, never stages what it was not asked to, and never discards work.
import assert from 'node:assert/strict';
import { execFileSync, spawnSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import test from 'node:test';
import { fileURLToPath } from 'node:url';

const repo = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
const base = fs.mkdtempSync(path.join(os.tmpdir(), 'agent-hook-'));
process.on('exit', () => fs.rmSync(base, { recursive: true, force: true }));
const HEADER = '<!-- Generated by scripts/gen-agent-files.mjs from AGENTS.md. Edit that and re-run it; never this file. -->\n\n';
// A git run by a test must not inherit a hook's or a worktree's view of the repository.
const env = Object.fromEntries(Object.entries(process.env).filter(([k]) => !k.startsWith('GIT_')));
const FILES = ['scripts/gen-agent-files.mjs', 'scripts/agent-files-pre-commit.mjs', 'scripts/install-git-hooks.mjs', 'scripts/agent-files.json',
  '.githooks', 'AGENTS.md', 'CLAUDE.md', '.agents', '.claude', '.opencode', 'opencode.json', '.gitattributes'];

function fixture(name, { install = true, commit = true } = {}) {
  const r = path.join(base, name);
  for (const p of FILES) fs.cpSync(path.join(repo, p), path.join(r, p), { recursive: true });
  fs.writeFileSync(path.join(r, 'README.md'), 'readme\n');
  const run = (cmd, args, extra = {}) => spawnSync(cmd, args, { cwd: r, encoding: 'utf8', env: { ...env, ...extra.env }, ...extra });
  const git = (...a) => run('git', ['-c', 'user.email=t@t', '-c', 'user.name=t', ...a]);
  git('init', '-q');
  if (commit) { git('add', '-A'); git('-c', 'core.hooksPath=/dev/null', 'commit', '-qm', 'fixture'); }
  const prepare = () => run('node', [path.join(r, 'scripts', 'install-git-hooks.mjs')], { cwd: path.join(r, '.agents') });
  if (install) assert.equal(prepare().status, 0);
  const show = (rev, f) => { const s = git('show', `${rev}:${f}`); return s.status === 0 ? s.stdout : null; };
  const read = (f) => fs.readFileSync(path.join(r, f), 'utf8');
  const edit = (f, fn) => fs.writeFileSync(path.join(r, f), fn(read(f)));
  const gen = () => run('node', ['scripts/gen-agent-files.mjs']);
  return { r, git, run, show, read, edit, gen, prepare, status: () => git('status', '--porcelain').stdout };
}
const appendRule = (t, line) => t.replace('# Workflow rules (always loaded)\n', `# Workflow rules (always loaded)\n\n${line}\n`);

test('(a) a commit staging an AGENTS.md edit carries the regenerated CLAUDE.md, and leaves nothing behind', () => {
  const f = fixture('a');
  f.edit('AGENTS.md', (t) => appendRule(t, 'RULE-A'));
  f.git('add', 'AGENTS.md');
  const c = f.git('commit', '-qm', 'a');
  assert.equal(c.status, 0, c.stderr);
  assert.equal(f.show('HEAD', 'CLAUDE.md'), HEADER + f.show('HEAD', 'AGENTS.md'));
  assert.ok(f.show('HEAD', 'CLAUDE.md').includes('RULE-A'));
  assert.equal(f.status(), '', 'the index or the work tree differs from HEAD after the commit');
});

test('(b) a source the generator rejects refuses the commit, with the generator\'s message', () => {
  const f = fixture('b');
  f.edit('AGENTS.md', (t) => appendRule(t, 'see @notes.md'));
  f.git('add', 'AGENTS.md');
  const c = f.git('commit', '-qm', 'b');
  assert.notEqual(c.status, 0, 'the commit went through');
  assert.match(c.stderr, /AGENTS\.md has @notes\.md/);
  assert.equal(f.git('rev-list', '--count', 'HEAD').stdout.trim(), '1');
});

test('(c) a partly staged AGENTS.md commits a CLAUDE.md of the staged part only', () => {
  const f = fixture('c');
  f.edit('AGENTS.md', (t) => appendRule(t, 'HUNK-A'));
  f.git('add', 'AGENTS.md');
  f.edit('AGENTS.md', (t) => `${t}\nHUNK-B\n`);
  const c = f.git('commit', '-qm', 'c');
  assert.equal(c.status, 0, c.stderr);
  const claude = f.show('HEAD', 'CLAUDE.md');
  assert.ok(claude.includes('HUNK-A') && !claude.includes('HUNK-B'), 'the commit carries a copy of text that is not in it');
  assert.ok(f.read('AGENTS.md').includes('HUNK-B'), 'the unstaged hunk was lost');
});

test('(d) an unrelated modified file is not staged by the hook', () => {
  const f = fixture('d');
  f.edit('README.md', (t) => `${t}unrelated\n`);
  f.edit('AGENTS.md', (t) => appendRule(t, 'RULE-D'));
  f.git('add', 'AGENTS.md');
  assert.equal(f.git('commit', '-qm', 'd').status, 0);
  assert.equal(f.show('HEAD', 'README.md'), 'readme\n', 'the hook staged a file it was not asked to');
  assert.match(f.status(), /^ M README\.md$/m);
});

test('(e) prepare outside a git work tree exits 0 and says so', () => {
  const dir = fs.mkdtempSync(path.join(base, 'e-'));
  const p = spawnSync('node', [path.join(repo, 'scripts', 'install-git-hooks.mjs')], { cwd: dir, encoding: 'utf8', env: { ...env, GIT_CEILING_DIRECTORIES: base } });
  assert.equal(p.status, 0, p.stderr);
  assert.match(p.stdout, /not in a git work tree/);
});

test('(f) prepare leaves another core.hooksPath alone', () => {
  const f = fixture('f', { install: false });
  f.git('config', 'core.hooksPath', 'my-hooks');
  assert.equal(f.prepare().status, 0);
  assert.equal(f.git('config', '--get', 'core.hooksPath').stdout.trim(), 'my-hooks');
});

const COPIES = ['.claude/commands/work.md', '.agents/skills/work/SKILL.md', '.opencode/command/work.md'];

test('(g) a command removed with git rm takes its copies with it in the same commit', () => {
  const f = fixture('g');
  f.git('rm', '-q', '.agents/commands/work.md');
  const c = f.git('commit', '-qm', 'g');
  assert.equal(c.status, 0, c.stderr);
  for (const p of COPIES) assert.equal(f.show('HEAD', p), null, `${p} outlived its command`);
  assert.ok(!f.show('HEAD', 'scripts/agent-files.json').includes('.agents/commands/work.md'));
  assert.equal(f.status(), '');
});

test('(g\') copies already removed by hand, with the list stale, commit cleanly', () => {
  const f = fixture('g2');
  f.git('rm', '-q', '.agents/commands/work.md', ...COPIES);
  const c = f.git('commit', '-qm', 'g2');
  assert.equal(c.status, 0, c.stderr);
  assert.ok(!f.show('HEAD', 'scripts/agent-files.json').includes('.agents/commands/work.md'), 'the list still names the command');
});

test('(g\'\') the generator run and only AGENTS.md staged: the commit carries CLAUDE.md', () => {
  const f = fixture('g3');
  f.edit('AGENTS.md', (t) => appendRule(t, 'RULE-G3'));
  assert.equal(f.gen().status, 0);
  f.git('add', 'AGENTS.md');
  const c = f.git('commit', '-qm', 'g3');
  assert.equal(c.status, 0, c.stderr);
  assert.ok(f.show('HEAD', 'CLAUDE.md').includes('RULE-G3'));
  assert.equal(f.status(), '');
});

test('(h) a commit that names its paths is refused when a copy needs regenerating, and passes when none does', () => {
  const f = fixture('h');
  f.edit('AGENTS.md', (t) => appendRule(t, 'RULE-H'));
  const c = f.git('commit', '-qm', 'h', '--', 'AGENTS.md');
  assert.notEqual(c.status, 0, 'a partial commit went through, leaving the real index to revert CLAUDE.md');
  assert.match(c.stderr, /commit without paths/);
  f.edit('README.md', (t) => `${t}more\n`);
  const ok = f.git('commit', '-qm', 'h2', '--', 'README.md');
  assert.equal(ok.status, 0, ok.stderr);
});

test('(i) a staged hand edit to a copy is refused, and the edit survives', () => {
  const f = fixture('i');
  f.edit('.claude/rules/docs.md', (t) => `${t}edited by hand\n`);
  f.git('add', '.claude/rules/docs.md');
  const c = f.git('commit', '-qm', 'i');
  assert.notEqual(c.status, 0, 'the hand edit was overwritten');
  assert.match(c.stderr, /\.claude\/rules\/docs\.md is staged as neither HEAD's copy nor what its staged source generates/);
  assert.ok(f.read('.claude/rules/docs.md').includes('edited by hand'));
  assert.ok(f.git('show', ':.claude/rules/docs.md').stdout.includes('edited by hand'));
});

test('(i\') a copy generated from an older source is refused, with "run the generator"', () => {
  const f = fixture('i2');
  f.edit('AGENTS.md', (t) => appendRule(t, 'RULE-1'));
  assert.equal(f.gen().status, 0);
  f.edit('AGENTS.md', (t) => appendRule(t, 'RULE-2'));
  f.git('add', '-A');
  const c = f.git('commit', '-qm', 'i2');
  assert.notEqual(c.status, 0, 'a stale copy was committed or silently replaced');
  assert.match(c.stderr, /CLAUDE\.md is staged as neither[\s\S]*run node scripts\/gen-agent-files\.mjs/);
});

test('(j) with no node on PATH the commit goes through, and says the files were not regenerated', () => {
  const f = fixture('j');
  const bin = path.join(base, 'j-bin');
  fs.mkdirSync(bin);
  const gitBin = execFileSync('sh', ['-c', 'command -v git'], { encoding: 'utf8' }).trim();
  fs.symlinkSync(fs.realpathSync(gitBin), path.join(bin, 'git'));
  f.edit('README.md', (t) => `${t}j\n`);
  f.git('add', 'README.md');
  const c = f.run(path.join(bin, 'git'), ['-c', 'user.email=t@t', '-c', 'user.name=t', 'commit', '-qm', 'j'], { env: { PATH: bin } });
  assert.equal(c.status, 0, c.stderr);
  assert.match(c.stderr, /node is not on PATH/);
});

test('(k) prepare leaves core.hooksPath unset when the hooks directory has hooks of its own', () => {
  const f = fixture('k', { install: false });
  const hooks = path.join(f.r, '.git', 'hooks');
  fs.mkdirSync(hooks, { recursive: true });
  fs.writeFileSync(path.join(hooks, 'post-checkout'), '#!/bin/sh\n', { mode: 0o755 });
  const p = f.prepare();
  assert.equal(p.status, 0);
  assert.match(p.stdout, /has hooks of its own \(post-checkout\)/);
  assert.equal(f.git('config', '--get', 'core.hooksPath').status, 1, 'core.hooksPath was set over a hook of the user\'s');
});

test('(l) an untracked skill in .agents/skills/ does not reach an unrelated commit', () => {
  const f = fixture('l');
  fs.mkdirSync(path.join(f.r, '.agents/skills/mine'));
  fs.writeFileSync(path.join(f.r, '.agents/skills/mine/SKILL.md'), '---\nname: mine\ndescription: added by npx skills add\n---\n');
  f.edit('README.md', (t) => `${t}l\n`);
  f.git('add', 'README.md');
  const c = f.git('commit', '-qm', 'l');
  assert.equal(c.status, 0, c.stderr);
  assert.equal(f.show('HEAD', '.claude/skills/mine/SKILL.md'), null, 'a copy of an uncommitted skill was committed');
});

test('(m) a root commit gets its CLAUDE.md from the staged AGENTS.md', () => {
  const f = fixture('m', { commit: false });
  fs.rmSync(path.join(f.r, 'CLAUDE.md'));
  f.git('add', '-A');
  const c = f.git('commit', '-qm', 'm');
  assert.equal(c.status, 0, c.stderr);
  assert.equal(f.show('HEAD', 'CLAUDE.md'), HEADER + f.show('HEAD', 'AGENTS.md'));
});

// Found by #271's own commit: main's list named AGENTS.md and .agents/skills/gopnik* as generated,
// and the hook took the old list's word for it and refused to keep a source.
test('(n) a path an older list generated, that is now a source, is kept', () => {
  const f = fixture('n');
  const list = JSON.parse(f.read('scripts/agent-files.json'));
  list.files = { 'AGENTS.md': ['CLAUDE.md'], '.agents/skills/gopnik/SKILL.md': '.claude/skills/gopnik/SKILL.md', ...list.files };
  fs.writeFileSync(path.join(f.r, 'scripts/agent-files.json'), `${JSON.stringify(list, null, 2)}\n`);
  f.git('add', '-A'); f.git('-c', 'core.hooksPath=/dev/null', 'commit', '-qm', 'an older list');
  f.edit('AGENTS.md', (t) => appendRule(t, 'RULE-N'));
  f.git('add', 'AGENTS.md');
  const c = f.git('commit', '-qm', 'n');
  assert.equal(c.status, 0, c.stderr);
  for (const p of ['AGENTS.md', '.agents/skills/gopnik/SKILL.md']) assert.ok(f.show('HEAD', p), `${p} was removed as a stale copy`);
  assert.ok(f.show('HEAD', 'CLAUDE.md').includes('RULE-N'));
});

test('the hook is installed by prepare, and is executable', () => {
  const pkg = JSON.parse(fs.readFileSync(path.join(repo, 'frontend', 'package.json'), 'utf8'));
  assert.equal(pkg.scripts.prepare, 'node ../scripts/install-git-hooks.mjs');
  const mode = execFileSync('git', ['-C', repo, 'ls-files', '-s', '--', '.githooks/pre-commit'], { encoding: 'utf8', env }).split(' ')[0];
  assert.equal(mode, '100755', '.githooks/pre-commit is not committed executable');
});
